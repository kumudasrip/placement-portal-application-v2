from datetime import datetime, timedelta
from sqlalchemy import func

def register_tasks(celery, mail):    
    @celery.task(name="send_monthly_placement_report", bind=True)
    def send_monthly_placement_report(self):
        from models import db, User, Application
        from app import _flask_app
        
        try:
            if not _flask_app:
                return {"status": "error", "message": "Flask app not available"}
            
            with _flask_app.app_context():
                admins = User.query.filter_by(role="admin").all()
                if not admins:
                    return {"status": "error", "message": "No admin users found"}  
                now = datetime.utcnow()
                first_day_last_month = (now.replace(day=1) - timedelta(days=1)).replace(day=1)
                last_day_last_month = now.replace(day=1) - timedelta(days=1)
                
                selected_apps = Application.query.filter(
                    Application.status == 'selected',
                    Application.application_date >= first_day_last_month,
                    Application.application_date <= last_day_last_month
                ).all()

                total_placements = len(selected_apps)
                total_salary = 0.0
                parsed_count = 0
                avg_salary = 0.0
                total_applications = Application.query.filter(
                    Application.application_date >= first_day_last_month,
                    Application.application_date <= last_day_last_month
                ).count()
                
                def parse_salary_to_rupees(salary_text):
                    if salary_text is None:
                        return None
                    try:
                        return float(int(str(salary_text).strip()))
                    except Exception:
                        try:
                            return float(str(salary_text).strip())
                        except Exception:
                            return None

                for a in selected_apps:
                    salary_val = parse_salary_to_rupees(a.drive.salary)
                    if salary_val is not None:
                        total_salary += salary_val
                        parsed_count += 1

                avg_salary = (total_salary / parsed_count) if parsed_count > 0 else 0.0

                report_text = f"""
Hello Admin,

Here is your Monthly Placement Report for {first_day_last_month.strftime('%B %Y')}:

{'='*50}
PLACEMENT STATISTICS
{'='*50}

Total Placements Achieved:        {total_placements}
Total Applications Received:       {total_applications}
Average Salary Offered:            ₹{avg_salary:,.2f}
Total Salary Amount:               ₹{total_salary:,.2f}

{'='*50}

This report was automatically generated by the Placement Portal System.
For more details, please log in to the admin dashboard.

Best regards,
PPA Team
                """
                for admin in admins:
                    mail.send_message(
                        subject=f"Monthly Placement Report - {first_day_last_month.strftime('%B %Y')}",
                        recipients=[admin.email],
                        body=report_text
                    )
                
                return {
                    "status": "success",
                    "message": f"Report sent to {len(admins)} admin(s)",
                    "placements": total_placements,
                    "applications": total_applications
                }
        except Exception as e:
            return {"status": "error", "message": str(e)}
    
    @celery.task(name="send_visit_reminders", bind=True)
    def send_visit_reminders(self):
        from models import db, User, Student, PlacementDrive, Application
        from app import _flask_app
        
        try:
            if not _flask_app:
                return {"status": "error", "message": "Flask app not available"}
            
            with _flask_app.app_context():
                open_drives = PlacementDrive.query.filter_by(status="approved").all()
                if not open_drives:
                    return {"status": "info", "message": "No open drives found"}
                
                reminder_count = 0
                students = Student.query.filter_by(is_active=True, is_blacklisted=False).all()
                for student in students:
                    applied_drive_ids = [app.drive_id for app in student.applications]
                    unapplied_drives = [d for d in open_drives if d.id not in applied_drive_ids]    
                    if unapplied_drives:
                        drives_list = "\n".join(
                            [f"  • {drive.job_title} at {drive.company.name}\n    Salary: {drive.salary}\n    Location: {drive.location or 'TBD'}\n    Deadline: {drive.application_deadline.strftime('%d-%m-%Y') if drive.application_deadline else 'TBD'}"
                             for drive in unapplied_drives[:5]]
                        )
                        
                        reminder_text = f"""
Hi {student.name},

Great news! There are {len(unapplied_drives)} open placement drive(s) that you haven't applied to yet.
Don't miss these amazing opportunities!

{'='*60}
AVAILABLE PLACEMENT DRIVES
{'='*60}

{drives_list}

{'='*60}

Visit the student portal now and submit your applications!

Remember:
  • Each application strengthens your chances of placement
  • Check the eligibility criteria before applying
  • Submit your resume before the deadline

Best of luck!

Regards,
PPA Team
                        """
                        try:
                            mail.send_message(
                                subject="Placement Drive Reminder - Don't Miss Out!",
                                recipients=[student.user.email],
                                body=reminder_text
                            )
                            reminder_count += 1
                        except Exception as e:
                            print(f"Error sending reminder to {student.user.email}: {e}")
                
                return {
                    "status": "success",
                    "message": f"Reminders sent to {reminder_count} students",
                    "open_drives": len(open_drives)
                }
        except Exception as e:
            return {"status": "error", "message": str(e)}
    
    @celery.task(name="export_applications_to_csv")
    def export_applications_to_csv(student_id):
        from models import db, Student, Application
        import csv
        from io import StringIO
        
        try:
            student = Student.query.get(student_id)
            if not student:
                return {"status": "error", "message": "Student not found"}
            
            applications = Application.query.filter_by(student_id=student_id).all()
            si = StringIO()
            writer = csv.writer(si)
            writer.writerow(['Application ID', 'Company Name', 'Drive Title', 'Status', 'Date'])
            for a in applications:
                writer.writerow([
                    a.id,
                    a.drive.company.name,
                    a.drive.job_title,
                    a.status,
                    a.application_date.strftime('%Y-%m-%d')
                ])
            
            return si.getvalue()
        except Exception as e:
            return {"status": "error", "message": str(e)}
    try:
        globals()['export_applications_to_csv'] = export_applications_to_csv
    except Exception:
        pass